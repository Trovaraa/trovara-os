import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, expect, it, vi } from 'vitest'
const upload = vi.fn()
vi.mock('@/lib/api', () => ({ api: async () => ({ assets: [], packs: [] }), resolveMediaUrl: (url: string) => url }))
vi.mock('@/lib/brand-upload', () => ({ uploadBrandAsset: (...args: unknown[]) => upload(...args) }))
vi.mock('@/components/AppLayout.vue', () => ({ default: { template: '<div><slot /></div>' } }))
vi.mock('@/components/EditorDrawer.vue', () => ({ default: { props: ['open'], template: '<div v-if="open"><slot /></div>' } }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key, locale: { value: 'en' } }) }))
afterEach(() => { upload.mockReset() })
it('continues after a failed clip and retries only that file, preserving successes', async () => {
  const { default: View } = await import('./BrandKitsView.vue')
  const wrapper = mount(View)
  await flushPromises()
  await wrapper.findAll('button').find(button => button.text() === 'brandKits.newPack')!.trigger('click')
  const files = [new File(['a'], 'first.mov'), new File(['b'], 'second.mov'), new File(['c'], 'third.mov')]
  upload.mockResolvedValueOnce({ id: 'one', status: 'ready', originalName: 'first.mov', mediaKind: 'video' })
    .mockRejectedValueOnce(new Error('Connection interrupted'))
    .mockResolvedValueOnce({ id: 'three', status: 'ready', originalName: 'third.mov', mediaKind: 'video' })
  const input = wrapper.get('input[type=file]')
  Object.defineProperty(input.element, 'files', { value: files, configurable: true })
  await input.trigger('change')
  await flushPromises()
  expect(upload).toHaveBeenCalledTimes(3)
  expect(wrapper.text()).toContain('Connection interrupted')
  expect(wrapper.get('.upload-queue').findAll('li')).toHaveLength(3)
  upload.mockResolvedValueOnce({ id: 'two', status: 'ready', originalName: 'second.mov', mediaKind: 'video' })
  await wrapper.findAll('button').find(button => button.text() === 'brandKits.retryUpload')!.trigger('click')
  await flushPromises()
  expect(upload).toHaveBeenCalledTimes(4)
  expect(upload.mock.calls[3][0]).toBe(files[1])
  expect(wrapper.text()).not.toContain('Connection interrupted')
  wrapper.unmount()
})
